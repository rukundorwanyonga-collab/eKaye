class Inguzanyo {
  Inguzanyo({
    required this.id,
    required this.izina,
    required this.inguzanyoAmafaranga,
    required this.impamvu,
    required this.umwishingizi,
    required this.akagari,
    required this.umudugudu,
    required this.itariki,
    required this.itarikiNtarengwa,
    this.yarishyuye = false,
  });

  final String id;
  String izina;
  double inguzanyoAmafaranga;
  String impamvu;
  String umwishingizi;
  String akagari;
  String umudugudu;
  String itariki;
  String itarikiNtarengwa;
  bool yarishyuye;
}
